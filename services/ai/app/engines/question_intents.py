"""Распознавание вопросов оператора по ключевым словам.

Словарь живёт в коде, а не в сценарии, потому что набор вопросов оператора 112
задан регламентом и опросной картой: он конечный и одинаковый для пожара, ДТП
и запаха газа. Описывать одни и те же вопросы заново в каждом сценарии значит
через неделю получить разъехавшиеся формулировки, а генератору сценариев -
лишний повод что-нибудь сочинить.

Ключевые слова заданы основами слов, чтобы падежи и числа ловились сами:
"пострадав" покрывает и "пострадавшие", и "пострадавших".
"""

import re
from typing import Dict, List, Tuple

# Вопросы, которые раскрывают факты сценария.
# Порядок важен: при совпадении нескольких намерений берётся первое сверху,
# благодаря этому ответ на одну и ту же реплику всегда одинаковый.
QUESTION_INTENTS: Dict[str, Dict[str, Tuple[str, ...]]] = {
    "ADDRESS": {
        "patterns": (
            "адрес",
            "улиц",
            "куда ехать",
            "куда прислать",
            "где наход",
            "где это",
            "какой дом",
            "номер дома",
        ),
        "facts": ("address",),
    },
    "VICTIMS": {
        "patterns": (
            "пострадав",
            "ранен",
            "жертв",
            "кому то плохо",
            "кому нибудь плохо",
            "люди есть",
            "есть ли люди",
            "нужна ли скорая",
        ),
        "facts": ("victims",),
    },
    "CALLER_ID": {
        "patterns": (
            "представьтесь",
            "как вас зовут",
            "ваше имя",
            "ваша фамилия",
            "кто звонит",
            "назовите себя",
            "ваш телефон",
            "номер телефона",
        ),
        "facts": ("callerName", "callerPhone"),
    },
    "BUILDING": {
        "patterns": (
            "этаж",
            "подъезд",
            "домофон",
            "квартир",
            "как войти",
            "код двери",
        ),
        "facts": ("callerFloor", "floors", "intercom"),
    },
    "LANDMARK": {
        "patterns": (
            "ориентир",
            "рядом что",
            "что рядом",
            "как найти",
            "возле чего",
        ),
        "facts": ("landmark",),
    },
    "WHAT_HAPPENED": {
        "patterns": (
            "что случилось",
            "что произошло",
            "что у вас",
            "что горит",
            "что именно",
            "опишите",
            "расскажите",
        ),
        "facts": ("openFlame", "vehicles", "hazard"),
    },
}

# Реплики, которые не спрашивают о фактах, но меняют состояние абонента.
TONE_MARKERS: Dict[str, Tuple[str, ...]] = {
    "GREETING": (
        "служба 112",
        "служба сто двенадцать",
        "оператор",
        "здравствуйте",
        "добрый день",
        "добрый вечер",
        "слушаю вас",
    ),
    "CALMING": (
        "успокойтесь",
        "не волнуйтесь",
        "помощь уже",
        "помощь выехала",
        "мы вас слышим",
        "я вас слышу",
        "все будет хорошо",
    ),
}

_NON_LETTERS = re.compile(r"[^а-яa-z0-9]+")


def normalize(text: str) -> str:
    """Приводит реплику к виду, по которому можно искать ключевые слова.

    Нижний регистр, ё превращается в е, всё кроме букв и цифр становится
    пробелом. После этого "Адрес?!" и "адрес" совпадают.
    """
    lowered = text.lower().replace("ё", "е")
    return _NON_LETTERS.sub(" ", lowered).strip()


def match_question(text: str) -> str:
    """Возвращает код вопроса или пустую строку, если вопрос не распознан."""
    normalized = normalize(text)
    for intent, rule in QUESTION_INTENTS.items():
        if any(pattern in normalized for pattern in rule["patterns"]):
            return intent
    return ""


def match_tone(text: str) -> List[str]:
    """Возвращает пометки тона: приветствие, попытка успокоить."""
    normalized = normalize(text)
    return [
        marker
        for marker, patterns in TONE_MARKERS.items()
        if any(pattern in normalized for pattern in patterns)
    ]


def facts_for(intent: str) -> Tuple[str, ...]:
    """Ключи фактов, которые раскрывает этот вопрос, в порядке выдачи."""
    rule = QUESTION_INTENTS.get(intent)
    return rule["facts"] if rule else ()
